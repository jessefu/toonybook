/**
 * Innocent phrases hidden from the matcher before it runs.
 *
 * Removal, not exclusion: the phrase is blanked out of the text, and the
 * blocked term is then matched against what is left. So `杀菌` (sterilise) is
 * allowed while a bare `杀` still is not — this list is the only reason the
 * single-character Chinese terms can be on the list at all.
 *
 * There is no English section, and that is the point: Latin-script terms are
 * word-anchored, so `hell` does not match `hello`, `ass` does not match
 * `class`, and `sex` does not match `sextant`. Only Chinese, which has no word
 * boundaries, needs a list.
 */
export const ALLOWED_PHRASES: string[] = [
  '杀菌',
  '杀虫',
  '消毒',
  // 大麻 (marijuana) sits inside 大麻烦 (big trouble) and 大麻袋 (a big sack),
  // both of which belong in a children's book.
  '大麻烦',
  '大麻袋',
  '大麻布',
  '大麻绳',
  '大麻花',
  // Harmless compounds of the violence terms: tying a tight knot, working
  // hard, and a boom in knowledge.
  '打死结',
  '流血流汗',
  '信息爆炸',
  '知识爆炸',
];

/**
 * Everything blocked, flattened once at load so a request is a few hundred
 * regex tests over a string of at most a few hundred characters.
 */
export const BLOCKED_FLAT: { term: string; category: ModerationCategory }[] =
  Object.entries(BLOCKED_TERMS).flatMap(([category, terms]) =>
    terms.map((term) => ({ term, category: category as ModerationCategory }))
  );
