/**
 * What a children's picture book must never be about.
 *
 * Grouped by *why* a term is blocked rather than by language, because the user
 * message names the reason ("this idea contains violence"), and that reads the
 * same whichever language the term was written in.
 *
 * ## How to add a term
 *
 * - Write the **whole word**, and write the forms separately (`kill`, `kills`,
 *   `killed`, `killing`, `killer`). Matching is word-anchored for Latin script,
 *   so a bare stem does not catch its own inflections — and listing them
 *   explicitly is what keeps `ass` from matching `class` and `glass`.
 * - Leave out anything a children's story can innocently contain. `hit`, `shot`
 *   and `fight` are absent on purpose: a ball game, a photo and a pillow fight
 *   are all ordinary picture-book material, and a false positive here means a
 *   parent cannot make the book they wanted.
 * - For Chinese, prefer two-character terms over single characters. There are no
 *   word boundaries in Chinese text, so a single character matches inside every
 *   compound it appears in — `枪` would block `水枪` (water pistol), `刀` would
 *   block `剪刀` (scissors). The four single characters below (`杀`, `淫`, `娼`,
 *   `嫖`) are the exceptions, kept because they cannot appear in a children's
 *   book innocently; the one compound of `杀` that can is in `ALLOWED_PHRASES`.
 */
